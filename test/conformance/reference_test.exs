defmodule SequenceHash.Conformance.ReferenceTest do
  @moduledoc """
  Customization strings longer than the block size, checked against vectors
  generated by the upstream Python implementation
  (see test/vectors/reference/README.md). The CCTV vectors do not cover this.
  """
  use ExUnit.Case, async: true

  alias SequenceHash.{Algorithm, MAC}
  alias SequenceHash.Test.Vectors

  import Vectors, only: [hex: 1]

  @external_resource Path.join(Vectors.root(), "reference/long_customizer.json")

  test "the vectors exercise customizers longer than the block size" do
    for vector <- Vectors.long_customizer()["vectors"] do
      algorithm = Vectors.algorithm(vector["hash_name"])
      assert byte_size(hex(vector["customizer"])) > Algorithm.block_size(algorithm)
    end
  end

  for vector <- Vectors.long_customizer()["vectors"] do
    @vector vector
    test "#{vector["hash_name"]} F=#{vector["function_id"]} customizer #{div(byte_size(vector["customizer"]), 2)} bytes" do
      algorithm = Vectors.algorithm(@vector["hash_name"])
      inputs = Enum.map(@vector["inputs"], &hex/1)
      customizer = hex(@vector["customizer"])

      actual =
        case @vector["function_id"] do
          2 ->
            SequenceHash.hash(algorithm, inputs, customizer: customizer)

          1 ->
            {:ok, tag} = MAC.mac(algorithm, hex(@vector["key"]), inputs, customizer: customizer)
            tag
        end

      assert actual == hex(@vector["final_output"])
    end
  end
end
